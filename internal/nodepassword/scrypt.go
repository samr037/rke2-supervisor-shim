// Package nodepassword reproduces rke2's node-password handling.
//
// rke2 gives each node a random secret, kept at /etc/rancher/node/password on
// the node and stored server-side - hashed - as a Secret named
// "<node>.node-password.rke2" in kube-system. It is what stops one node from
// requesting certificates in another node's name.
//
// The hash format and scrypt parameters below are byte-compatible with
// k3s/rke2 (pkg/authenticator/hash), so the Secrets this shim writes are
// readable by a real rke2 server and vice versa. TestVerifyRealRKE2Hash pins
// that against a hash generated by an actual rke2 server.
package nodepassword

import (
	"context"
	"crypto/rand"
	"crypto/subtle"
	"encoding/base64"
	"errors"
	"fmt"
	"runtime"

	"golang.org/x/crypto/scrypt"
)

const (
	version    = 1
	hashFormat = "$%d:%x:%d:%d:%d:%s"

	// Identical to k3s hash.NewSCrypt(). N is a log2 exponent, not the value.
	paramN       = 15
	paramR       = 8
	paramP       = 1
	paramKeyLen  = 64
	paramSaltLen = 8

	// Bounds on parameters read back from a stored hash. They leave headroom
	// above what rke2 writes (N=2^15, r=8, p=1, 64-byte key) while keeping a
	// single verification under ~64 MiB, and a derived key long enough that
	// matching it by chance is not a practical attack.
	maxParamN    = 16
	maxParamR    = 16
	maxParamP    = 4
	minKeyLen    = 32
	maxKeyLen    = 1024
	minPassword  = 8
	maxPassword  = 256
	slotsPerProc = 2
)

var (
	ErrMismatch = errors.New("node password mismatch")
	// ErrMalformedHash means the stored hash is not one rke2 or this shim
	// could have written; it is never evaluated.
	ErrMalformedHash = errors.New("malformed node password hash")
)

// scryptKey is indirected so tests can observe how it is called.
var scryptKey = scrypt.Key

// scryptSlots bounds concurrent scrypt runs. Each costs 128*N*r bytes (32 MiB
// at rke2's parameters) and tens of milliseconds of CPU, and every node-scoped
// certificate request costs one; unbounded, a burst of requests is a memory
// exhaustion attack.
var scryptSlots = make(chan struct{}, slotsPerProc*runtime.GOMAXPROCS(0))

func runScrypt(ctx context.Context, password, salt []byte, n, r, p, keyLen int) ([]byte, error) {
	select {
	case scryptSlots <- struct{}{}:
	case <-ctx.Done():
		return nil, ctx.Err()
	}
	defer func() { <-scryptSlots }()
	return scryptKey(password, salt, n, r, p, keyLen)
}

// ValidatePassword rejects node passwords outside sane bounds before any
// hashing is done. rke2 generates 32 hex characters; the bounds only exclude
// what no agent sends.
func ValidatePassword(password string) error {
	if len(password) < minPassword || len(password) > maxPassword {
		return fmt.Errorf("node password must be %d to %d bytes, got %d", minPassword, maxPassword, len(password))
	}
	return nil
}

// CreateHash hashes a node password for storage.
func CreateHash(secret string) (string, error) {
	return createHash(context.Background(), secret)
}

func createHash(ctx context.Context, secret string) (string, error) {
	salt := make([]byte, paramSaltLen)
	if _, err := rand.Read(salt); err != nil {
		return "", err
	}
	dk, err := runScrypt(ctx, []byte(secret), salt, 1<<paramN, paramR, paramP, paramKeyLen)
	if err != nil {
		return "", err
	}
	enc := base64.RawStdEncoding.EncodeToString(dk)
	return fmt.Sprintf(hashFormat, version, salt, paramN, paramR, paramP, enc), nil
}

// VerifyHash reports whether secret matches a stored hash, in constant time.
func VerifyHash(hash, secret string) error {
	return verifyHash(context.Background(), hash, secret)
}

func verifyHash(ctx context.Context, hash, secret string) error {
	var (
		ver, n uint
		r, p   int
		enc    string
		salt   []byte
	)
	if _, err := fmt.Sscanf(hash, hashFormat, &ver, &salt, &n, &r, &p, &enc); err != nil {
		return fmt.Errorf("%w: %v", ErrMalformedHash, err)
	}
	if ver != version {
		return fmt.Errorf("hash version %d is not supported (want %d)", ver, version)
	}
	// Sscanf stops at whitespace and tolerates other slack, so anything that
	// does not re-encode to exactly the stored string is refused.
	if fmt.Sprintf(hashFormat, ver, salt, n, r, p, enc) != hash {
		return fmt.Errorf("%w: not in canonical form", ErrMalformedHash)
	}
	dk, err := base64.RawStdEncoding.DecodeString(enc)
	if err != nil {
		return fmt.Errorf("%w: %v", ErrMalformedHash, err)
	}
	// Honour the parameters recorded in the hash rather than our defaults, so
	// hashes written by other rke2 versions still verify - but only within
	// bounds, because the hash is data and must not be able to dictate how
	// much memory and CPU a request costs, or shrink the key to a guessable
	// size.
	switch {
	case n < 1 || n > maxParamN:
		return fmt.Errorf("%w: N=2^%d outside 2^1..2^%d", ErrMalformedHash, n, maxParamN)
	case r < 1 || r > maxParamR:
		return fmt.Errorf("%w: r=%d outside 1..%d", ErrMalformedHash, r, maxParamR)
	case p < 1 || p > maxParamP:
		return fmt.Errorf("%w: p=%d outside 1..%d", ErrMalformedHash, p, maxParamP)
	case len(dk) < minKeyLen || len(dk) > maxKeyLen:
		return fmt.Errorf("%w: derived key of %d bytes outside %d..%d", ErrMalformedHash, len(dk), minKeyLen, maxKeyLen)
	}
	want, err := runScrypt(ctx, []byte(secret), salt, 1<<n, r, p, len(dk))
	if err != nil {
		return err
	}
	if subtle.ConstantTimeCompare(dk, want) != 1 {
		return ErrMismatch
	}
	return nil
}
